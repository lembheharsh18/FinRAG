# In-memory tag storage (would be database in production)
_tags_store: Dict[str, Dict[str, List[str]]] = {}  # user_id -> doc_id -> [tags]


class TagRequest(BaseModel):
    document_id: str
    tags: List[str] = Field(..., max_length=20)


class TagResponse(BaseModel):
    document_id: str
    tags: List[str]


@router.post(
    "/documents/{document_id}/tags",
    response_model=TagResponse,
    summary="Set Document Tags",
    description="Add or update tags for a document."
)
async def set_tags(
    document_id: str,
    request: TagRequest,
    user_id: str = Depends(get_user_id)
):
    """Set tags for a document."""
    if user_id not in _tags_store:
        _tags_store[user_id] = {}
    
    # Clean and deduplicate tags
    clean_tags = list(set([t.strip().lower() for t in request.tags if t.strip()]))[:10]
    _tags_store[user_id][document_id] = clean_tags
    
    return TagResponse(document_id=document_id, tags=clean_tags)


@router.get(
    "/documents/{document_id}/tags",
    response_model=TagResponse,
    summary="Get Document Tags",
    description="Get tags for a document."
)
async def get_tags(
    document_id: str,
    user_id: str = Depends(get_user_id)
):
    """Get tags for a document."""
    tags = _tags_store.get(user_id, {}).get(document_id, [])
    return TagResponse(document_id=document_id, tags=tags)


@router.get(
    "/tags",
    summary="Get All Tags",
    description="Get all unique tags used by the user."
)
async def get_all_tags(
    user_id: str = Depends(get_user_id)
):
    """Get all unique tags across all documents."""
    user_tags = _tags_store.get(user_id, {})
    all_tags = set()
    for tags in user_tags.values():
        all_tags.update(tags)
    return {"tags": sorted(list(all_tags))}


@router.delete(
    "/documents/{document_id}/tags/{tag}",
    summary="Remove Tag",
    description="Remove a specific tag from a document."
)
async def remove_tag(
    document_id: str,
    tag: str,
    user_id: str = Depends(get_user_id)
):
    """Remove a tag from a document."""
    tags = _tags_store.get(user_id, {}).get(document_id, [])
    clean_tag = tag.strip().lower()
    if clean_tag in tags:
        tags.remove(clean_tag)
    return {"document_id": document_id, "tags": tags}
